#!/usr/bin/env python3
"""Generate strict Rust, TypeScript and Go DTOs from the sole JSON Schema source."""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "crates/eos-plugin-protocol/schema/contracts.json"


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def rust_type(node):
    if "$ref" in node:
        return node["$ref"].split("/")[-1]
    kind = node.get("type")
    if kind == "array":
        return f"Vec<{rust_type(node['items'])}>"
    if kind == "object" and isinstance(node.get("additionalProperties"), dict):
        return f"std::collections::BTreeMap<String, {rust_type(node['additionalProperties'])}>"
    return {"string": "String", "boolean": "bool", "integer": "u64", "number": "f64"}.get(kind, "serde_json::Value")


def ts_type(node):
    if "$ref" in node:
        return node["$ref"].split("/")[-1]
    if "enum" in node:
        return " | ".join(json.dumps(v) for v in node["enum"])
    kind = node.get("type")
    if kind == "array":
        return f"Array<{ts_type(node['items'])}>"
    if kind == "object" and isinstance(node.get("additionalProperties"), dict):
        return f"Record<string, {ts_type(node['additionalProperties'])}>"
    return {"string": "string", "boolean": "boolean", "integer": "number", "number": "number"}.get(kind, "unknown")


def go_type(node):
    if "$ref" in node:
        return node["$ref"].split("/")[-1]
    kind = node.get("type")
    if kind == "array":
        return "[]" + go_type(node["items"])
    if kind == "object" and isinstance(node.get("additionalProperties"), dict):
        return "map[string]" + go_type(node["additionalProperties"])
    return {"string": "string", "boolean": "bool", "integer": "uint64", "number": "float64"}.get(kind, "json.RawMessage")


def outputs():
    raw = SCHEMA.read_bytes()
    schema = json.loads(raw)
    digest = hashlib.sha256(raw).hexdigest()
    rs = [f"// @generated by scripts/generate.py; schema sha256={digest}", "use serde::{Serialize, Deserialize};"]
    defaults=[]
    ts = [f"// @generated; schema sha256={digest}"]
    go = [f"// Code generated by eos-plugins; schema sha256={digest}. DO NOT EDIT.", "package pluginprotocol", 'import "encoding/json"']
    for name, definition in schema["$defs"].items():
        required = set(definition.get("required", []))
        derive=("Serialize, Deserialize" if definition.get("x-rust-serialize") else "Deserialize") if definition.get("x-sensitive") else "Debug, Clone, Serialize, Deserialize, PartialEq"
        rs += [f"#[derive({derive})]", "#[serde(deny_unknown_fields)]", f"pub struct {name} {{"]
        if not definition.get("x-sensitive"): ts.append(f"export interface {name} {{")
        go.append(f"type {name} struct {{")
        for field, node in definition["properties"].items():
            optional = field not in required
            defaulted = "default" in node
            ty = rust_type(node)
            if optional and not defaulted:
                ty = f"Option<{ty}>"
            attrs = [f'rename = "{field}"']
            if optional:
                default_value=node.get("default")
                special_default=defaulted and ((ty=="String" and default_value!="") or (ty=="serde_json::Value" and default_value is not None))
                if special_default:
                    helper="default_"+snake(name)+"_"+snake(field)
                    attrs.append(f'default = "{helper}"')
                    literal=json.dumps(default_value,ensure_ascii=False)
                    expression=f"String::from({literal})" if ty=="String" else f"serde_json::json!({literal})"
                    defaults.append(f"fn {helper}() -> {ty} {{ {expression} }}")
                else:
                    attrs.append("default")
                if not defaulted:
                    attrs.append('skip_serializing_if = "Option::is_none"')
            rs.append(f"    #[serde({', '.join(attrs)})]")
            rust_name = node.get("x-rust-name", snake(field))
            if rust_name in {"type", "ref", "match", "mod"}:
                rust_name = "r#" + rust_name
            rs.append(f"    pub {rust_name}: {ty},")
            if not definition.get("x-sensitive"): ts.append(f"  {json.dumps(field)}{'?' if optional else ''}: {ts_type(node)};")
            go_name = node.get("x-go-name", field[0].upper() + field[1:])
            go_ty = go_type(node)
            if optional and not defaulted:
                go_ty = "*" + go_ty
            omit = ",omitempty" if optional else ""
            go.append(f'    {go_name} {go_ty} `json:"{field}{omit}"`')
        rs.append("}")
        if not definition.get("x-sensitive"): ts.append("}")
        go.append("}")
    rs += defaults
    rust_source=subprocess.run(["rustfmt","--edition","2021","--emit","stdout"],input="\n".join(rs)+"\n",capture_output=True,text=True,check=True).stdout
    go_source=subprocess.run(["gofmt"],input="\n".join(go)+"\n",capture_output=True,text=True,check=True).stdout
    return {
        ROOT / "crates/eos-plugin-protocol/src/generated.rs": rust_source,
        ROOT / "sdk/typescript/src/protocol.ts": "\n".join(ts) + "\n",
        ROOT / "sdk/go/protocol.go": go_source,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, value in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != value:
                raise SystemExit(f"stale generated contract: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    print("contract generation: OK")


if __name__ == "__main__":
    main()
